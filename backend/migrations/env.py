"""Alembic environment (async).

Generated by ``alembic init -t async migrations`` and modified in five places:
metadata wiring, runtime URL injection, ``compare_*`` flags, ``NullPool``, and a
``sys.path`` entry so ``import app...`` resolves when alembic runs as a
subprocess.
"""

import asyncio
import os
import sys
from logging.config import fileConfig

from alembic import context
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

# `backend/` is the import root for `app`. Alembic is invoked with `cwd=backend`,
# but as a subprocess (`python -m alembic`) `sys.path[0]` is not necessarily the
# cwd, so make the dependency explicit rather than relying on invocation style.
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# Importing the model package is what registers every table on `Base.metadata`.
# Without it `alembic revision --autogenerate` emits an EMPTY migration and
# reports no error at all.
import app.db.models  # noqa: E402, F401
from app.config import get_settings  # noqa: E402
from app.db.base import Base  # noqa: E402

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# `alembic.ini` deliberately carries no `sqlalchemy.url` (FOUND-05). The URL is
# injected here from the environment, at runtime.
#
# The `%` -> `%%` escape is REQUIRED: `set_main_option` writes into a
# `ConfigParser` that performs pyformat interpolation, so a percent-encoded
# character in a URL-escaped password (`%40` for `@`) would raise
# `InterpolationSyntaxError` before a single migration ran.
config.set_main_option("sqlalchemy.url", get_settings().async_database_url.replace("%", "%%"))

target_metadata = Base.metadata


def run_migrations_offline() -> None:
    """Run migrations in 'offline' mode (emit SQL, no DBAPI needed)."""
    url = config.get_main_option("sqlalchemy.url")
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_type=True,
        compare_server_default=True,
    )

    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        # Without these two, `alembic check` and autogenerate ignore a changed
        # column type or a changed server default, so the models and the schema
        # can drift apart while every command still reports success.
        compare_type=True,
        compare_server_default=True,
    )

    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    """Create an async engine and associate a connection with the context."""
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        # Migrations are one-shot: a pool would keep connections open past the
        # end of the process for no benefit.
        poolclass=pool.NullPool,
    )

    async with connectable.connect() as connection:
        await connection.run_sync(do_run_migrations)

    await connectable.dispose()


def run_migrations_online() -> None:
    """Run migrations in 'online' mode."""
    asyncio.run(run_async_migrations())


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
