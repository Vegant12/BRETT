# The user's stated goal is a LEAN BULK. There is no `users.goal` column and none is being added;
# the goal shapes these threshold VALUES and nothing structural. If the goal changes, these five
# constants are the ones to revisit -- and nothing else in the module.

# D-11. The stricter end of the published 0.25-0.5%/week lean-bulk band, chosen to keep gains lean
# rather than tolerate a faster, fattier surplus. Evaluated against D-16's SMOOTHED rate.
WEIGHT_GAIN_TOO_FAST_PERCENT_PER_WEEK = Decimal("0.25")

# D-12. Deliberately asymmetric: loss is not the goal, but a loss this fast during a bulk is a
# clear signal something is off -- undereating, illness, or a tracking error -- and is worth
# surfacing regardless of the stated goal.
WEIGHT_LOSS_TOO_FAST_PERCENT_PER_WEEK = Decimal("-1.00")

# The "weight stable" dead-band. CONTEXT.md supplies the two OUTER thresholds but not this one,
# and blueprint 26's enum needs it to distinguish `weight_stable` from `likely_muscle_gain` and
# `likely_fat_loss`. One tenth of D-11's own threshold rather than an independent invention: at
# this user's ~65 kg that is ~65 g/week, comfortably below what a 7-day average over 3-6 weigh-ins
# can resolve, so a narrower band would classify measurement noise as a direction.
WEIGHT_STABLE_BAND_PERCENT_PER_WEEK = Decimal("0.10")

# D-20. A whole-body verdict must not turn on one accessory lift; three is the smallest number for
# which a majority exists at all.
RECOMP_MIN_CLASSIFIED_EXERCISES = 3

# D-20. Symmetric, ONE constant, exact in Decimal because it compares against an integer ratio.
# "More than a quarter of your classified exercises are net-improving" is a sentence a coach can
# check by counting.
RECOMP_PROGRESSION_NET_BAND = Decimal("0.25")

# The window the progression signal and the context volume are read over. Matches PROG-03's D-19
# default so "am I recomping" and "am I plateaued" describe the same block of training.
RECOMP_LOOKBACK_WEEKS = 12

_NET_QUANTUM = Decimal("0.0001")

INTERPRETATION_DISCLAIMER = (
    "Decision support from body-weight trend and training progression only. "
    "Not a medical or diagnostic claim, and not a body-composition measurement."
)


def aggregate_progression(verdicts: Sequence[TrendVerdict]) -> AggregateProgression:
    """D-20: the net-progression score over the exercises PROG-02 was able to classify.

    Pure and synchronous, so the band and the three-exercise minimum are testable with no
    container. Every count is reported alongside the score, because a net of -0.04 over 28
    exercises and a net of -0.04 over 3 are very different claims.
    """
    improving = sum(1 for v in verdicts if v is TrendVerdict.IMPROVING)
    stable = sum(1 for v in verdicts if v is TrendVerdict.STABLE)
    declining = sum(1 for v in verdicts if v is TrendVerdict.DECLINING)
    unclear = sum(1 for v in verdicts if v is TrendVerdict.UNCLEAR)
    classified = improving + stable + declining

    if classified < RECOMP_MIN_CLASSIFIED_EXERCISES:
        return AggregateProgression(
            verdict=TrendVerdict.UNCLEAR,
            signal=ProgressionSignal.INSUFFICIENT,
            # None, not 0.0: "we could not compute a score" is a different fact from "the score
            # is exactly neutral", and a zero here would read as the latter.
            net_score=None,
            classified_exercises=classified,
            improving=improving,
            stable=stable,
            declining=declining,
            unclear=unclear,
        )

    net = (Decimal(improving - declining) / Decimal(classified)).quantize(_NET_QUANTUM)
    if net > RECOMP_PROGRESSION_NET_BAND:
        signal, verdict = ProgressionSignal.POSITIVE, TrendVerdict.IMPROVING
    elif net < -RECOMP_PROGRESSION_NET_BAND:
        signal, verdict = ProgressionSignal.NEGATIVE, TrendVerdict.DECLINING
    else:
        signal, verdict = ProgressionSignal.NEUTRAL, TrendVerdict.STABLE
    return AggregateProgression(
        verdict=verdict,
        signal=signal,
        net_score=net,
        classified_exercises=classified,
        improving=improving,
        stable=stable,
        declining=declining,
        unclear=unclear,
    )


class _WeightBucket(StrEnum):
    """Internal. The five weight-rate bands, plus the null case, that key the label matrix."""

    TOO_FAST_GAIN = "too_fast_gain"
    ON_TARGET_GAIN = "on_target_gain"
    STABLE = "stable"
    LOSING = "losing"
    TOO_FAST_LOSS = "too_fast_loss"
    INSUFFICIENT = "insufficient"


def _weight_bucket(rate_percent_per_week: Decimal | None) -> _WeightBucket:
    """D-10 through D-12 plus the stable band, as one ordered ladder.

    Boundary conventions, stated once because both sides are tested: the too-fast thresholds are
    STRICT (+0.25 is on target, +0.26 is too fast; -1.00 is losing, -1.01 is too fast), and the
    stable band is INCLUSIVE at both edges (-0.10 and +0.10 both read as stable).
    """
    if rate_percent_per_week is None:
        return _WeightBucket.INSUFFICIENT
    if rate_percent_per_week > WEIGHT_GAIN_TOO_FAST_PERCENT_PER_WEEK:
        return _WeightBucket.TOO_FAST_GAIN
    if rate_percent_per_week > WEIGHT_STABLE_BAND_PERCENT_PER_WEEK:
        return _WeightBucket.ON_TARGET_GAIN
    if rate_percent_per_week >= -WEIGHT_STABLE_BAND_PERCENT_PER_WEEK:
        return _WeightBucket.STABLE
    if rate_percent_per_week >= WEIGHT_LOSS_TOO_FAST_PERCENT_PER_WEEK:
        return _WeightBucket.LOSING
    return _WeightBucket.TOO_FAST_LOSS


# The column order of `_MATRIX_ROWS` below. Named rather than implied, because `zip(...,
# strict=True)` turns a short or long row into an ImportError at module load instead of a
# plausible-looking mislabelling discovered months later.
_SIGNAL_ORDER: tuple[ProgressionSignal, ...] = (
    ProgressionSignal.POSITIVE,
    ProgressionSignal.NEUTRAL,
    ProgressionSignal.NEGATIVE,
    ProgressionSignal.INSUFFICIENT,
)

# D-20's label matrix, as DATA rather than nested ifs so every one of the 24 combinations is
# visible in one place and a missing branch is a KeyError rather than a silent fallthrough.
# Values are blueprint 26's seven enum members -- there is no eighth, and adding one would change
# the contract Phase 6 codes against.
#
# The four too-fast / on-target / insufficient rows repeat one status across all four signals, and
# that repetition is deliberate rather than a candidate for compression: D-11 and D-12 are SAFETY
# signals, and "you are gaining 0.6%/week" needs saying whether or not the bench is going up.
#
# `likely_recomp_progressing` appears ONLY in the stable and losing rows and ONLY under a positive
# signal. That is textbook recomposition -- weight flat or slightly down while strength rises --
# and it matches the published convention that strength is the LEADING indicator while the scale
# and the tape are lagging.
_MATRIX_ROWS: tuple[tuple[_WeightBucket, tuple[RecompositionStatus, ...]], ...] = (
    (
        _WeightBucket.TOO_FAST_GAIN,
        (
            RecompositionStatus.WEIGHT_GAIN_TOO_FAST,
            RecompositionStatus.WEIGHT_GAIN_TOO_FAST,
            RecompositionStatus.WEIGHT_GAIN_TOO_FAST,
            RecompositionStatus.WEIGHT_GAIN_TOO_FAST,
        ),
    ),
    (
        _WeightBucket.ON_TARGET_GAIN,
        (
            RecompositionStatus.LIKELY_MUSCLE_GAIN,
            RecompositionStatus.LIKELY_MUSCLE_GAIN,
            RecompositionStatus.LIKELY_MUSCLE_GAIN,
            RecompositionStatus.LIKELY_MUSCLE_GAIN,
        ),
    ),
    (
        _WeightBucket.STABLE,
        (
            RecompositionStatus.LIKELY_RECOMP_PROGRESSING,
            RecompositionStatus.WEIGHT_STABLE,
            RecompositionStatus.WEIGHT_STABLE,
            RecompositionStatus.WEIGHT_STABLE,
        ),
    ),
    (
        _WeightBucket.LOSING,
        (
            RecompositionStatus.LIKELY_RECOMP_PROGRESSING,
            RecompositionStatus.LIKELY_FAT_LOSS,
            RecompositionStatus.LIKELY_FAT_LOSS,
            RecompositionStatus.LIKELY_FAT_LOSS,
        ),
    ),
    (
        _WeightBucket.TOO_FAST_LOSS,
        (
            RecompositionStatus.WEIGHT_LOSS_TOO_FAST,
            RecompositionStatus.WEIGHT_LOSS_TOO_FAST,
            RecompositionStatus.WEIGHT_LOSS_TOO_FAST,
            RecompositionStatus.WEIGHT_LOSS_TOO_FAST,
        ),
    ),
    (
        _WeightBucket.INSUFFICIENT,
        (
            RecompositionStatus.INSUFFICIENT_DATA,
            RecompositionStatus.INSUFFICIENT_DATA,
            RecompositionStatus.INSUFFICIENT_DATA,
            RecompositionStatus.INSUFFICIENT_DATA,
        ),
    ),
)

# MappingProxyType for the reason `exercise_map.py`'s tables use it: a caller must not be able to
# retune a health verdict at runtime.
_LABEL_MATRIX: Mapping[tuple[_WeightBucket, ProgressionSignal], RecompositionStatus] = (
    MappingProxyType(
        {
            (bucket, signal): status
            for bucket, statuses in _MATRIX_ROWS
            for signal, status in zip(_SIGNAL_ORDER, statuses, strict=True)
        }
    )
)


def classify_recomposition(
    *, rate_percent_per_week: Decimal | None, signal: ProgressionSignal
) -> RecompositionStatus:
    """Cross the weight-rate ladder with the progression signal. Pure, total, and table-driven.

    A ``KeyError`` here would mean the matrix lost a combination, which is exactly the failure a
    nested-if implementation hides behind a final ``else``. Every one of the 24 pairs is asserted
    by the tests.
    """
    return _LABEL_MATRIX[(_weight_bucket(rate_percent_per_week), signal)]


async def get_recomposition_status(
    session: AsyncSession, *, user_id: uuid.UUID
) -> RecompositionResult:
    """BODY-02: a recomposition verdict from the weight trend and the training-progression signal.

    Takes no date range, for the same reason ``get_body_weight_trend`` does not: "where does my
    recomposition stand" is always anchored on today.

    Session positional, ``user_id`` keyword-only with no default (ASVS V4). The caller owns the
    transaction; nothing here writes.
    """
    weight_trend = await get_body_weight_trend(session, user_id=user_id)
    # The anchor is REUSED from the body-weight call rather than recomputed. Recomputing it would
    # let the two halves of one answer straddle a local midnight and describe different "todays".
    anchor = weight_trend.anchor_day
    window_start = anchor - dt.timedelta(days=7 * RECOMP_LOOKBACK_WEEKS - 1)

    # Reused, never re-implemented: `get_exercise_trends` is the ONE definition of "improving",
    # and a second copy here is how the recomposition verdict and the progression tool would
    # eventually disagree about the same exercise over the same weeks.
    trends = await get_exercise_trends(
        session, user_id=user_id, start_day=window_start, end_day=anchor
    )
    progression = aggregate_progression([e.verdict for e in trends.exercises])

    # Reported for CONTEXT only. BODY-02's requirement text names training volume as an input to
    # the picture, not to the label: the classification is the weight rate crossed with the
    # progression signal, and adding volume to it would make the verdict depend on a figure that
    # rises during a deload-free overreach as readily as during productive training.
    training_volume = await get_weekly_volume(
        session, user_id=user_id, start_day=window_start, end_day=anchor
    )

    return RecompositionResult(
        status=classify_recomposition(
            # D-16's SMOOTHED rate, never D-17's raw single-week delta.
            rate_percent_per_week=weight_trend.trend_rate_percent_per_week,
            signal=progression.signal,
        ),
        # A required field, always populated -- including on the insufficient path, which is the
        # response most likely to be quoted without its context.
        disclaimer=INTERPRETATION_DISCLAIMER,
        weight_trend=weight_trend,
        progression_signal=progression,
        training_volume=training_volume,
        # ALL THREE resources: this response reads body measurements AND workouts AND exercise
        # templates (the D-03 e1RM gate). It is only as fresh as the stalest of the three, and a
        # stale template sync silently changes the progression signal with no error anywhere.
        freshness=await build_freshness(
            session, user_id=user_id, resources=FRESHNESS_RESOURCES_ALL
        ),
    )
