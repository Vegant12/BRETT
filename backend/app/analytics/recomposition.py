"""Recomposition status (BODY-02). Composition only -- no SQL of its own beyond the envelope.

Calls ``bodyweight.get_body_weight_trend`` and ``progression.get_exercise_trends`` rather than
re-deriving either. One computation with two consumers beats two definitions of "improving", and
the same argument ``volume.get_muscle_group_volume`` makes for reusing ``_fold_week_totals``.

**Decision support, never a diagnosis.** ``RecompositionResult.disclaimer`` is a REQUIRED FIELD,
not documentation, so that a Phase 6 serialization change cannot drop it. A fixed constant safety
label is NOT the "backend-generated coaching prose" REQUIREMENTS.md excludes -- that exclusion
targets generated insight, and this string is generated by nothing. Do not delete it as prose.

**Weight sets the direction; progression refines the label within it.** The weight rate is D-16's
SMOOTHED four-week figure and nothing else. D-17's raw single-week ``latest_week_delta_kg`` is
present in the nested ``weight_trend`` for context and is never classified against: on live data
it reads +0.72%/week off one week of glycogen noise, nearly THREE TIMES D-11's threshold. This
paragraph is the ONLY place that field name may appear in this module -- if it turns up beside a
call or a comparison, the classifier has acquired the noisy input it exists to avoid.

**The too-fast rows ignore progression deliberately.** D-11 and D-12 are safety signals. "You are
gaining 0.6%/week" needs saying whether or not your bench is going up -- a fast gain with improving
lifts is still a fattier bulk than intended.

**The net score, not a plurality.** On live data 9 improving / 9 stable / 10 declining across 28
exercises returns `declining` under plurality -- off a ONE-EXERCISE margin -- and `stable` under
the net score, which is the honest reading of a 9-vs-10 split. ``unclear`` exercises are excluded
from the DENOMINATOR, not counted as stable: counting them as stable would let a mostly-untracked
training block dilute a real signal toward the one verdict that carries no information.

**On-target gain reports ``likely_muscle_gain`` regardless of progression, and that is not an
overstatement.** Blueprint 26's enum has no "gaining on target but lifts flat" member, and
``weight_stable`` would be factually false. The label claims only "gaining at a rate consistent
with muscle gain". The nuance is carried by the required ``progression_signal`` field, so Claude
reading ``likely_muscle_gain`` beside a ``negative`` signal can say "you are gaining at a lean-bulk
rate but your lifts are going backwards -- that gain is probably not muscle."

**Body fat and waist are not inputs, because there is no data.** ``fat_percent`` is 0 of 123 live
rows, ``lean_mass_kg`` 0 of 123, and ``waist_cm`` 15 of 123 with a three-month gap between the two
most recent values. Blueprint 24's "combines body weight, waist, body fat if available" resolves
here to weight plus training. Do not design a body-fat input into this module.

**``insufficient_data`` is the expected answer on live data today**, because the D-16 anchor window
holds zero weigh-ins after a real 52-day logging gap. It is a first-class tested path.
"""

